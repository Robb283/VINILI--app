const assert = require('node:assert/strict');
require('../app/static/price-comparison.js');
const {parse, difference, compare} = globalThis.FirstPressPrices;
const item = value => ({compatibility:'compatible', price:{currency:'EUR',value}});
const data = {status:'ok', items:[item(30),item(40),item(60)],price:{available:true,currency:'EUR',count:3,low:35,high:50,median:40}};
assert.equal(parse(''),null);
assert.equal(parse(' 40,50 '),40.5);
assert.equal(parse('40.50'),40.5);
for(const value of ['0','-5','1e2','40,555','1.000,00','Infinity','1000001'])assert.ok(Number.isNaN(parse(value)),value);
assert.equal(compare(null,data),null);
assert.equal(compare(NaN,data).state,'invalid');
assert.equal(compare(34,data).state,'below');
assert.equal(compare(35,data).state,'inline');
assert.equal(compare(50,data).state,'inline');
assert.equal(compare(51,data).state,'above');
assert.equal(compare(60,data).medianDifference,50);
assert.equal(compare(80,{...data,items:data.items.slice(0,2)}).state,'limited');
assert.equal(compare(80,{...data,price:{available:false},items:[item(30)]}).count,1);
assert.equal(compare(80,{...data,items:[{...item(30),compatibility:'unverified'},{...item(30),price:{currency:'USD',value:30}}]}).state,'unavailable');
assert.equal(compare(80,{status:'error'}).state,'unavailable');
assert.equal(compare(80,{...data,price:{...data.price,high:20}}).state,'limited');
assert.deepEqual(difference(50,item(40)),{euros:10,percent:25,direction:'above'});
assert.deepEqual(difference(30,item(40)),{euros:-10,percent:-25,direction:'below'});
assert.deepEqual(difference(40,item(40)),{euros:0,percent:0,direction:'equal'});
assert.equal(difference(40,item(0)),null);
assert.equal(difference(null,item(40)),null);
console.log('Price comparison checks passed');
